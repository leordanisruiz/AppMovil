ALTER TABLE "DW_CONFIG".usuarios_app
    ADD COLUMN IF NOT EXISTS rol_id SMALLINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = '"DW_CONFIG".usuarios_app'::regclass
          AND conname = 'ck_usuarios_app_rol_id'
    ) THEN
        ALTER TABLE "DW_CONFIG".usuarios_app
            ADD CONSTRAINT ck_usuarios_app_rol_id
            CHECK (rol_id IS NULL OR rol_id IN (1, 2));
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS "DW_CONFIG".tipos_tareas (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO "DW_CONFIG".tipos_tareas (nombre)
VALUES ('Capacitación'), ('Actividad recreativa'), ('Exposición')
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE "DW_OPERACIONAL".tareas_operador
    ADD COLUMN IF NOT EXISTS novedades_ids JSONB NOT NULL DEFAULT '[]'::jsonb;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'DW_OPERACIONAL'
          AND table_name = 'tareas_operador'
          AND column_name = 'novedad_id'
    ) THEN
        EXECUTE '
            UPDATE "DW_OPERACIONAL".tareas_operador
            SET novedades_ids = jsonb_build_array(novedad_id)
            WHERE novedad_id IS NOT NULL
              AND novedades_ids = ''[]''::jsonb
        ';
        ALTER TABLE "DW_OPERACIONAL".tareas_operador
            DROP COLUMN novedad_id;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'DW_OPERACIONAL'
          AND table_name = 'tareas_operador'
          AND column_name = 'consecutivo'
    ) THEN
        ALTER TABLE "DW_OPERACIONAL".tareas_operador
            DROP COLUMN consecutivo;
    END IF;
END
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = '"DW_OPERACIONAL".tareas_operador'::regclass
          AND conname = 'ck_tareas_operador_novedades_ids'
    ) THEN
        ALTER TABLE "DW_OPERACIONAL".tareas_operador
            ADD CONSTRAINT ck_tareas_operador_novedades_ids
            CHECK (jsonb_typeof(novedades_ids) = 'array');
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS ix_tareas_operador_novedades_ids_gin
    ON "DW_OPERACIONAL".tareas_operador
    USING GIN (novedades_ids jsonb_path_ops);

ALTER TABLE "DW_CONFIG".expo_push_outbox
    ALTER COLUMN id_novedad DROP NOT NULL;

ALTER TABLE "DW_CONFIG".expo_push_outbox
    ADD COLUMN IF NOT EXISTS task_id BIGINT
        REFERENCES "DW_OPERACIONAL".tareas_operador (id) ON DELETE CASCADE;

ALTER TABLE "DW_CONFIG".expo_push_outbox
    DROP CONSTRAINT IF EXISTS uq_expo_push_outbox_recipient;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = '"DW_CONFIG".expo_push_outbox'::regclass
          AND conname = 'ck_expo_push_outbox_event'
    ) THEN
        ALTER TABLE "DW_CONFIG".expo_push_outbox
            ADD CONSTRAINT ck_expo_push_outbox_event
            CHECK ((id_novedad IS NOT NULL) <> (task_id IS NOT NULL));
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_expo_push_outbox_novelty_recipient
    ON "DW_CONFIG".expo_push_outbox (id_novedad, token_hash)
    WHERE id_novedad IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_expo_push_outbox_task_recipient
    ON "DW_CONFIG".expo_push_outbox (task_id, token_hash)
    WHERE task_id IS NOT NULL;

COMMIT;

CREATE SCHEMA IF NOT EXISTS "DW_CONFIG";

CREATE TABLE IF NOT EXISTS "DW_CONFIG".usuarios_app (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo_documento VARCHAR(32) NOT NULL,
    identificacion VARCHAR(64) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuarios_app
        PRIMARY KEY (id),
    CONSTRAINT uq_usuarios_app_documento_identificacion
        UNIQUE (tipo_documento, identificacion),
    CONSTRAINT ck_usuarios_app_tipo_documento_not_blank
        CHECK (BTRIM(tipo_documento) <> ''),
    CONSTRAINT ck_usuarios_app_identificacion_not_blank
        CHECK (BTRIM(identificacion) <> ''),
    CONSTRAINT ck_usuarios_app_bcrypt_hash_length
        CHECK (LENGTH(password_hash) = 60)
);

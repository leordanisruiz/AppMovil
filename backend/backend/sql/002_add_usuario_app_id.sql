BEGIN;

CREATE SCHEMA IF NOT EXISTS "DW_CONFIG";

DO $$
BEGIN
    IF to_regclass('"DW_CONFIG".usuarios_app') IS NULL
       AND to_regclass('public.usuarios_app') IS NOT NULL THEN
        ALTER TABLE public.usuarios_app SET SCHEMA "DW_CONFIG";
    ELSIF to_regclass('"DW_CONFIG".usuarios_app') IS NOT NULL
       AND to_regclass('public.usuarios_app') IS NOT NULL THEN
        RAISE EXCEPTION
            'Both public.usuarios_app and "DW_CONFIG".usuarios_app exist; '
            'resolve the duplicate tables before applying this migration.';
    ELSIF to_regclass('"DW_CONFIG".usuarios_app') IS NULL THEN
        RAISE EXCEPTION
            'Neither public.usuarios_app nor "DW_CONFIG".usuarios_app exists.';
    END IF;
END
$$;

ALTER TABLE "DW_CONFIG".usuarios_app
    ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

DO $$
DECLARE
    current_primary_key TEXT;
BEGIN
    SELECT constraint_row.conname
    INTO current_primary_key
    FROM pg_constraint AS constraint_row
    WHERE constraint_row.conrelid = '"DW_CONFIG".usuarios_app'::regclass
      AND constraint_row.contype = 'p'
      AND pg_get_constraintdef(constraint_row.oid) <> 'PRIMARY KEY (id)';

    IF current_primary_key IS NOT NULL THEN
        EXECUTE format(
            'ALTER TABLE "DW_CONFIG".usuarios_app DROP CONSTRAINT %I',
            current_primary_key
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint AS constraint_row
        WHERE constraint_row.conrelid = '"DW_CONFIG".usuarios_app'::regclass
          AND constraint_row.contype = 'p'
          AND pg_get_constraintdef(constraint_row.oid) = 'PRIMARY KEY (id)'
    ) THEN
        ALTER TABLE "DW_CONFIG".usuarios_app
            ADD CONSTRAINT pk_usuarios_app PRIMARY KEY (id);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint AS constraint_row
        WHERE constraint_row.conrelid = '"DW_CONFIG".usuarios_app'::regclass
          AND constraint_row.contype = 'u'
          AND constraint_row.conname =
              'uq_usuarios_app_documento_identificacion'
    ) THEN
        ALTER TABLE "DW_CONFIG".usuarios_app
            ADD CONSTRAINT uq_usuarios_app_documento_identificacion
            UNIQUE (tipo_documento, identificacion);
    END IF;
END
$$;

COMMIT;

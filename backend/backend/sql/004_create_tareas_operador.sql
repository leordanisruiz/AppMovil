BEGIN;

CREATE SCHEMA IF NOT EXISTS "DW_OPERACIONAL";

CREATE TABLE IF NOT EXISTS "DW_OPERACIONAL".tareas_operador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    novedades_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    operador_id BIGINT NOT NULL,
    tipo_tarea VARCHAR(120) NOT NULL,
    descripcion TEXT NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion VARCHAR(128) NOT NULL,
    estado VARCHAR(16) NOT NULL DEFAULT 'PENDIENTE',
    evidencias JSONB NOT NULL DEFAULT '{"evidencias": []}'::jsonb,
    CONSTRAINT ck_tareas_operador_estado
        CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA', 'CERRADO')),
    CONSTRAINT ck_tareas_operador_novedades_ids
        CHECK (jsonb_typeof(novedades_ids) = 'array'),
    CONSTRAINT ck_tareas_operador_evidencias
        CHECK (
            jsonb_typeof(evidencias) = 'object'
            AND jsonb_typeof(evidencias->'evidencias') = 'array'
        )
);

CREATE INDEX IF NOT EXISTS ix_tareas_operador_operador_estado_fecha
    ON "DW_OPERACIONAL".tareas_operador (
        operador_id,
        estado,
        fecha_creacion DESC
    );

CREATE INDEX IF NOT EXISTS ix_tareas_operador_evidencias_gin
    ON "DW_OPERACIONAL".tareas_operador
    USING GIN (evidencias jsonb_path_ops);

CREATE INDEX IF NOT EXISTS ix_tareas_operador_novedades_ids_gin
    ON "DW_OPERACIONAL".tareas_operador
    USING GIN (novedades_ids jsonb_path_ops);

COMMIT;

BEGIN;

ALTER TABLE "DW_CONFIG".expo_push_poll_state
    ADD COLUMN IF NOT EXISTS categorias_inicializadas BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_novelty_state (
    fuente VARCHAR(8) NOT NULL CHECK (fuente IN ('ico', 'sico')),
    id_novedad BIGINT NOT NULL,
    codigo_operador VARCHAR(64),
    categoria VARCHAR(16) NOT NULL CHECK (categoria IN ('ico', 'isv', 'inasistencias', 'danos', 'otras')),
    revision BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (fuente, id_novedad)
);

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_novelty_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente VARCHAR(8) NOT NULL,
    id_novedad BIGINT NOT NULL,
    codigo_operador VARCHAR(64) NOT NULL,
    categoria VARCHAR(16) NOT NULL,
    revision BIGINT NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (fuente, id_novedad, revision)
);

ALTER TABLE "DW_CONFIG".expo_push_outbox
    ADD COLUMN IF NOT EXISTS novelty_event_id BIGINT
        REFERENCES "DW_CONFIG".expo_push_novelty_events (id);

ALTER TABLE "DW_CONFIG".expo_push_outbox
    DROP CONSTRAINT IF EXISTS expo_push_outbox_id_novedad_fkey;

DROP INDEX IF EXISTS "DW_CONFIG".uq_expo_push_outbox_novelty_recipient;
CREATE UNIQUE INDEX IF NOT EXISTS uq_expo_push_outbox_legacy_novelty_recipient
    ON "DW_CONFIG".expo_push_outbox (id_novedad, token_hash)
    WHERE id_novedad IS NOT NULL AND novelty_event_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_expo_push_outbox_event_recipient
    ON "DW_CONFIG".expo_push_outbox (novelty_event_id, token_hash)
    WHERE novelty_event_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS "DW_CONFIG".novedades_vistas (
    codigo_operador VARCHAR(64) NOT NULL,
    categoria VARCHAR(16) NOT NULL CHECK (categoria IN ('ico', 'isv', 'inasistencias', 'danos')),
    id_novedad BIGINT NOT NULL,
    visto_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (codigo_operador, categoria, id_novedad)
);

COMMIT;

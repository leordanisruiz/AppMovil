BEGIN;

CREATE SCHEMA IF NOT EXISTS "DW_CONFIG";

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    token_ciphertext TEXT NOT NULL,
    tipo_documento VARCHAR(32) NOT NULL,
    identificacion VARCHAR(64) NOT NULL,
    plataforma VARCHAR(16) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_expo_push_tokens_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_expo_push_tokens_platform
        CHECK (plataforma IN ('ios', 'android')),
    CONSTRAINT ck_expo_push_tokens_identity
        CHECK (BTRIM(tipo_documento) <> '' AND BTRIM(identificacion) <> '')
);

CREATE INDEX IF NOT EXISTS ix_expo_push_tokens_active_identity
    ON "DW_CONFIG".expo_push_tokens (
        tipo_documento,
        identificacion
    )
    WHERE activo = TRUE;

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_poll_state (
    id SMALLINT PRIMARY KEY,
    inicializado BOOLEAN NOT NULL DEFAULT FALSE,
    ultimo_sondeo TIMESTAMPTZ,
    CONSTRAINT ck_expo_push_poll_state_singleton CHECK (id = 1)
);

INSERT INTO "DW_CONFIG".expo_push_poll_state (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_seen_novelties (
    id_novedad BIGINT PRIMARY KEY,
    codigo_operador BIGINT,
    primera_vez_vista TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    historica BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS "DW_CONFIG".expo_push_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_novedad BIGINT NOT NULL
        REFERENCES "DW_CONFIG".expo_push_seen_novelties (id_novedad),
    token_hash CHAR(64) NOT NULL
        REFERENCES "DW_CONFIG".expo_push_tokens (token_hash),
    estado VARCHAR(16) NOT NULL DEFAULT 'pendiente',
    intentos INTEGER NOT NULL DEFAULT 0,
    receipt_intentos INTEGER NOT NULL DEFAULT 0,
    proximo_intento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_until TIMESTAMPTZ,
    claim_id UUID,
    expo_ticket_id VARCHAR(128),
    ultimo_error VARCHAR(64),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_expo_push_outbox_recipient
        UNIQUE (id_novedad, token_hash),
    CONSTRAINT ck_expo_push_outbox_state
        CHECK (
            estado IN (
                'pendiente',
                'procesando',
                'recibo_pendiente',
                'enviado',
                'fallido',
                'cancelado'
            )
        ),
    CONSTRAINT ck_expo_push_outbox_attempts
        CHECK (intentos >= 0 AND receipt_intentos >= 0)
);

CREATE INDEX IF NOT EXISTS ix_expo_push_outbox_ready
    ON "DW_CONFIG".expo_push_outbox (proximo_intento, id)
    WHERE estado IN ('pendiente', 'procesando', 'recibo_pendiente');

COMMIT;
